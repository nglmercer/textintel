fn logistic_decision_score(result: &ComparisonResult) -> f64 {
    let features = feature_vector(result);
    let mut logit = LOGISTIC_BIAS;
    for (weight, value) in LOGISTIC_WEIGHTS.iter().zip(logistic_order_indices().iter()) {
        logit += weight * features[*value];
    }
    let logit = logit.clamp(-60.0, 60.0);
    1.0 / (1.0 + (-logit).exp())
}

