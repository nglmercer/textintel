/// Feature values extracted once per comparison, in the fixed baked
/// order the ensemble was trained with.
fn feature_vector(result: &ComparisonResult) -> [f64; 47] {
    let mut f = [0.0f64; 47];
    {
        let c = result.character.unwrap_or(0.0);
        f[0] = c * c;
    }
    f[1] = result.character.unwrap_or(0.0);
    f[2] = result.character.unwrap_or(0.0) * result.lexicon_validity * result.single_word_pair;
    f[3] = result.confusable_swap;
    f[4] = result.substring_containment * result.character.unwrap_or(0.0).max(0.5);
    f[5] = result.contextual_semantic;
    f[6] = result.cross_language_semantic;
    f[7] = result.cross_script_agreement;
    f[8] = result.cross_script_pair;
    f[9] = result.decoded_similarity.unwrap_or(0.0);
    f[10] = result.entity_agreement;
    f[11] = result.entity_conflict;
    f[12] = result.exact_decode;
    f[13] = result.decoded_similarity.unwrap_or(0.0) * (1.0 - result.exact_decode);
    f[14] = result.lexical.unwrap_or(0.0);
    f[15] = result.lexicon_validity;
    f[16] = result.multi_swap_antonym;
    f[17] = result.multi_swap_synonym_coverage;
    f[18] = result.normalized_identity;
    f[19] = result.obfuscation_similarity.unwrap_or(0.0);
    f[20] = result.phonetic.unwrap_or(0.0);
    f[21] = if result.phonetic.is_some() { 1.0 } else { 0.0 };
    f[22] = result.semantic.unwrap_or(0.0);
    f[23] = if result.semantic.is_some() { 1.0 } else { 0.0 };
    {
        let s = result.semantic.unwrap_or(0.0);
        f[24] = s * s;
    }
    f[25] = result.semantic_without_lexical_overlap;
    f[26] = result.semantic.unwrap_or(0.0) * result.character.unwrap_or(0.0);
    f[27] = result.single_word_exact;
    f[28] = result.single_word_pair;
    f[29] = result.substring_containment;
    f[30] = result.swap_antonym;
    f[31] = result.swapped_word_similarity * result.swapped_phonetic;
    f[32] = result.swapped_word_similarity * result.lexicon_validity;
    f[33] = result.swap_synonym;
    f[34] = result.swapped_phonetic;
    f[35] = result.swapped_word_similarity;
    f[36] = result.symbolic.unwrap_or(0.0);
    f[37] = if result.symbolic.is_some() { 1.0 } else { 0.0 };
    f[38] = result.transliteration_compatibility;
    f[39] = result.transliteration_confidence.unwrap_or(0.0);
    f[40] = result.transliteration_semantic_agreement;
    f[41] = result.transliteration_semantic_conflict;
    f[42] = result.transliteration_similarity.unwrap_or(0.0);
    f[43] = result.transliteration_similarity.unwrap_or(0.0)
        * result.transliteration_confidence.unwrap_or(0.0);
    f[44] = result.character.unwrap_or(0.0)
        * (1.0 - result.lexicon_validity)
        * result.single_word_pair.max(0.5);
    f[45] = result.valid_swap_similarity;
    f[46] = result.visual.unwrap_or(0.0);
    for value in &mut f {
        if !value.is_finite() {
            *value = 0.0;
        }
    }
    f
}

