// logistic weight order: char_sq,character,confusable_pressure,confusable_swap,containment_character,contextual_semantic,cross_language_semantic,cross_script_agreement,cross_script_pair,decoded_similarity,entity_agreement,entity_conflict,exact_decode,inexact_decoded_overlap,lexical,lexicon_validity,normalized_identity,obfuscation_similarity,phonetic,phonetic_present,semantic,semantic_present,semantic_sq,semantic_without_lexical_overlap,semantic_x_char,single_word_exact,single_word_pair,substring_containment,swap_form,swap_meaning_valid,swapped_phonetic,swapped_word_similarity,symbolic,symbolic_present,transliteration_compatibility,transliteration_confidence,transliteration_semantic_agreement,transliteration_semantic_conflict,transliteration_similarity,transliteration_weighted,typo_signal,valid_swap_similarity,visual
fn logistic_decision_score(result: &ComparisonResult) -> f64 {
    let features = feature_vector(result);
    let mut logit = LOGISTIC_BIAS;
    for (weight, value) in LOGISTIC_WEIGHTS.iter().zip(logistic_order_indices().iter()) {
        logit += weight * features[*value];
    }
    let logit = logit.clamp(-60.0, 60.0);
    1.0 / (1.0 + (-logit).exp())
}

