/// Feature values extracted once per comparison, in the fixed baked
/// order the ensemble was trained with.
fn feature_vector(result: &ComparisonResult) -> [f64; 43] {
    let mut f = [0.0f64; 43];
    let semantic = result.semantic.unwrap_or(0.0);
    let character = result.character.unwrap_or(0.0);
    { let c = result.character.unwrap_or(0.0); f[0] = c * c; }
    f[1] = result.character.unwrap_or(0.0);
    f[2] = result.character.unwrap_or(0.0) * result.lexicon_validity * result.single_word_pair;
    f[3] = result.confusable_swap;
    f[4] = result.substring_containment * result.character.unwrap_or(0.0).max(0.5);
    f[5] = result.contextual_semantic;
    f[6] = result.cross_language_semantic;
    f[7] = result.cross_script_agreement;
    f[8] = result.cross_script_pair;
    f[9] = result.decoded_similarity.unwrap_or(0.0);
    f[10] = result.entity_agreement;
    f[11] = result.entity_conflict;
    f[12] = result.exact_decode;
    f[13] = result.decoded_similarity.unwrap_or(0.0) * (1.0 - result.exact_decode);
    f[14] = result.lexical.unwrap_or(0.0);
    f[15] = result.lexicon_validity;
    f[16] = result.normalized_identity;
    f[17] = result.obfuscation_similarity.unwrap_or(0.0);
    f[18] = result.phonetic.unwrap_or(0.0);
    f[19] = if result.phonetic.is_some() { 1.0 } else { 0.0 };
    f[20] = result.semantic.unwrap_or(0.0);
    f[21] = if result.semantic.is_some() { 1.0 } else { 0.0 };
    { let s = result.semantic.unwrap_or(0.0); f[22] = s * s; }
    f[23] = result.semantic_without_lexical_overlap;
    f[24] = result.semantic.unwrap_or(0.0) * result.character.unwrap_or(0.0);
    f[25] = result.single_word_exact;
    f[26] = result.single_word_pair;
    f[27] = result.substring_containment;
    f[28] = result.swapped_word_similarity * result.swapped_phonetic;
    f[29] = result.swapped_word_similarity * result.lexicon_validity;
    f[30] = result.swapped_phonetic;
    f[31] = result.swapped_word_similarity;
    f[32] = result.symbolic.unwrap_or(0.0);
    f[33] = if result.symbolic.is_some() { 1.0 } else { 0.0 };
    f[34] = result.transliteration_compatibility;
    f[35] = result.transliteration_confidence.unwrap_or(0.0);
    f[36] = result.transliteration_semantic_agreement;
    f[37] = result.transliteration_semantic_conflict;
    f[38] = result.transliteration_similarity.unwrap_or(0.0);
    f[39] = result.transliteration_similarity.unwrap_or(0.0) * result.transliteration_confidence.unwrap_or(0.0);
    f[40] = result.character.unwrap_or(0.0) * (1.0 - result.lexicon_validity) * result.single_word_pair.max(0.5);
    f[41] = result.valid_swap_similarity;
    f[42] = result.visual.unwrap_or(0.0);
    for value in &mut f {
        if !value.is_finite() {
            *value = 0.0;
        }
    }
    f
}

